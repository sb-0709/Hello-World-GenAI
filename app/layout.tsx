import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import Script from "next/script";
import "./globals.css";
import Navbar from './components/Navbar'

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

// Runs before paint so the page never flashes the wrong theme: if the user
// previously picked light/dark via the toggle, apply it to <html> right
// away. If they never chose, we leave data-theme unset and globals.css's
// `@media (prefers-color-scheme: dark)` block takes over automatically.
const themeInitScript = `
  try {
    var t = localStorage.getItem('theme');
    if (t === 'light' || t === 'dark') {
      document.documentElement.setAttribute('data-theme', t);
    }
  } catch (e) {}
`;

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
      <html
          lang="en"
          className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
          // The theme script sets data-theme on the client before hydration,
          // which won't match the server-rendered markup (which has none) —
          // that's expected and harmless, so we tell React not to warn about it.
          suppressHydrationWarning
      >
      <body className="min-h-full flex flex-col">
      <Script id="theme-init" strategy="beforeInteractive">
        {themeInitScript}
      </Script>
      <Navbar />
      {children}
      </body>
      </html>
  );
}